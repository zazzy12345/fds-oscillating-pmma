!> \brief V2c-D static-density, time-dependent-composition manufactured solution.
!> \details This module is deliberately a narrow verification-only path.  It
!> never reads a numerical scalar state to construct a source term and it
!> never uses the legacy PERIODIC_TEST manufactured-solution hooks.

MODULE MMSD_FUNCTIONS

USE PRECISION_PARAMETERS
USE GLOBAL_CONSTANTS
USE MESH_POINTERS
USE TYPES, ONLY: SPECIES_MIXTURE
USE COMP_FUNCTIONS, ONLY: CHECKREAD,SHUTDOWN
USE PHYSICAL_FUNCTIONS, ONLY: GET_SPECIFIC_GAS_CONSTANT,GET_SPECIFIC_HEAT,GET_SENSIBLE_ENTHALPY_Z
USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE

IMPLICIT NONE (TYPE,EXTERNAL)
PRIVATE

PUBLIC READ_MMSD,CHECK_MMSD_SCOPE,MMSD_EVALUATE_STATE,MMSD_EVALUATE_SOURCE, &
       MMSD_ADD_DENSITY_STAGE,MMSD_ADD_DIVERGENCE_HEAT,MMSD_ADD_DIVERGENCE_SPECIES, &
       MMSD_WRITE_DIAGNOSTICS,MMSD_OUTPUT_VALUE,MMSD_ACTIVE,MMSD_SCOPE_ACCEPTED,MMSD_INITIAL_STATE_TIME

LOGICAL :: MMSD_ACTIVE=.FALSE.,MMSD_SCOPE_ACCEPTED=.FALSE.,MMSD_DIAGNOSTICS_WRITTEN=.FALSE.
LOGICAL :: MMSD_REQUIRE_FRAME=.FALSE.,MMSD_REQUIRE_PHYSICAL_PRESSURE_GAUGE=.FALSE.
INTEGER :: MMSD_SPEC_INDEX(2)=0
CHARACTER(LABEL_LENGTH) :: MMSD_ID='null',MMSD_FRAME_ID='null',MMSD_THERMAL_MODE='null'
REAL(EB) :: MMSD_LZ=0._EB,MMSD_P_REF=0._EB,MMSD_T_REF=0._EB,MMSD_YH_MEAN=0._EB, &
            MMSD_YH_AMPLITUDE=0._EB,MMSD_RHO_AMPLITUDE=0._EB,MMSD_OMEGA_M=0._EB, &
            MMSD_T_REF_M=0._EB,MMSD_INITIAL_STATE_TIME=0._EB,MMSD_DIFFUSIVITY=0._EB, &
            MMSD_RHO_REF=0._EB,MMSD_Z0=0._EB

CONTAINS


!> \brief Read the single V2c-D MMSD namelist. Absent card is a strict no-op.

SUBROUTINE READ_MMSD(DT)

REAL(EB), INTENT(IN) :: DT
CHARACTER(LABEL_LENGTH) :: ID,FRAME_ID,SPEC_ID(2),THERMAL_MODE
REAL(EB) :: LZ,P_REF,T_REF,YH_MEAN,YH_AMPLITUDE,RHO_AMPLITUDE,OMEGA_M,T_REF_M,INITIAL_STATE_TIME,DIFFUSIVITY
LOGICAL :: ENABLE,REQUIRE_FRAME,REQUIRE_PHYSICAL_PRESSURE_GAUGE
INTEGER :: IOS,N_MMSD_READ,N,NS

NAMELIST /MMSD/ DIFFUSIVITY,ENABLE,FRAME_ID,ID,INITIAL_STATE_TIME,LZ,OMEGA_M,P_REF,REQUIRE_FRAME, &
                REQUIRE_PHYSICAL_PRESSURE_GAUGE,RHO_AMPLITUDE,SPEC_ID,T_REF,T_REF_M,THERMAL_MODE,YH_AMPLITUDE,YH_MEAN

MMSD_ACTIVE=.FALSE.
MMSD_SCOPE_ACCEPTED=.FALSE.
N_MMSD_READ=0
REWIND(LU_INPUT) ; INPUT_FILE_LINE_NUMBER=0

MMSD_LOOP: DO
   CALL CHECKREAD('MMSD',LU_INPUT,IOS) ; IF (STOP_STATUS==SETUP_STOP) RETURN
   IF (IOS==1) EXIT MMSD_LOOP
   ID='null'; FRAME_ID='null'; SPEC_ID='null'; THERMAL_MODE='null'
   ENABLE=.FALSE.; REQUIRE_FRAME=.FALSE.; REQUIRE_PHYSICAL_PRESSURE_GAUGE=.FALSE.
   LZ=-1._EB; P_REF=-1._EB; T_REF=-1._EB; YH_MEAN=-1._EB; YH_AMPLITUDE=-1._EB; RHO_AMPLITUDE=-2._EB
   OMEGA_M=-1._EB; T_REF_M=-HUGE(1._EB); INITIAL_STATE_TIME=-HUGE(1._EB); DIFFUSIVITY=-1._EB
   READ(LU_INPUT,MMSD,END=10,ERR=20,IOSTAT=IOS)
   20 IF (IOS>0) THEN
      CALL SHUTDOWN('ERROR(MMSD): Problem with MMSD line.') ; RETURN
   ENDIF
   N_MMSD_READ=N_MMSD_READ+1
   IF (N_MMSD_READ>1) THEN
      CALL SHUTDOWN('ERROR(MMSD): Only one MMSD line is permitted.') ; RETURN
   ENDIF
ENDDO MMSD_LOOP
10 REWIND(LU_INPUT) ; INPUT_FILE_LINE_NUMBER=0

IF (N_MMSD_READ==0) RETURN
IF (.NOT.ALL(IEEE_IS_FINITE([DT,LZ,P_REF,T_REF,YH_MEAN,YH_AMPLITUDE,RHO_AMPLITUDE,OMEGA_M, &
                              T_REF_M,INITIAL_STATE_TIME,DIFFUSIVITY]))) THEN
   CALL SHUTDOWN('ERROR(MMSD): All MMSD real inputs, including TIME DT, must be finite.') ; RETURN
ENDIF
IF (.NOT.ENABLE) THEN
   CALL SHUTDOWN('ERROR(MMSD): A present MMSD line must set ENABLE=.TRUE..') ; RETURN
ENDIF
IF (ID=='null' .OR. THERMAL_MODE/='EOS_SOURCE_NO_CONDUCTION') THEN
   CALL SHUTDOWN('ERROR(MMSD): Require a non-null ID and THERMAL_MODE=''EOS_SOURCE_NO_CONDUCTION''.') ; RETURN
ENDIF
IF (ANY(SPEC_ID=='null') .OR. SPEC_ID(1)==SPEC_ID(2)) THEN
   CALL SHUTDOWN('ERROR(MMSD): Require two distinct tracked SPEC_ID values.') ; RETURN
ENDIF
IF (LZ<=0._EB .OR. P_REF<=0._EB .OR. T_REF<=0._EB .OR. OMEGA_M<=0._EB .OR. DIFFUSIVITY<=0._EB) THEN
   CALL SHUTDOWN('ERROR(MMSD): LZ, P_REF, T_REF, OMEGA_M, and DIFFUSIVITY must be positive.') ; RETURN
ENDIF
IF (YH_MEAN-ABS(YH_AMPLITUDE)<=0._EB .OR. YH_MEAN+ABS(YH_AMPLITUDE)>=1._EB .OR. ABS(RHO_AMPLITUDE)>=1._EB) THEN
   CALL SHUTDOWN('ERROR(MMSD): Analytic mass fractions or density are non-positive/out of bounds.') ; RETURN
ENDIF
IF (ABS(T_REF_M)>100._EB*EPSILON(1._EB) .OR. ABS(INITIAL_STATE_TIME)>100._EB*EPSILON(1._EB)) THEN
   CALL SHUTDOWN('ERROR(MMSD): This implementation fixes T_REF_M=INITIAL_STATE_TIME=0.') ; RETURN
ENDIF

IF (N_TRACKED_SPECIES/=2) THEN
   CALL SHUTDOWN('ERROR(MMSD): Exactly two tracked gas species are required.') ; RETURN
ENDIF
DO N=1,2
   DO NS=1,N_TRACKED_SPECIES
      IF (TRIM(SPECIES_MIXTURE(NS)%ID)==TRIM(SPEC_ID(N))) MMSD_SPEC_INDEX(N)=NS
   ENDDO
   IF (MMSD_SPEC_INDEX(N)==0) THEN
      CALL SHUTDOWN('ERROR(MMSD): SPEC_ID is not a tracked gas species.') ; RETURN
   ENDIF
ENDDO
! SPEC_ID(1) is LIGHT and SPEC_ID(2) is HEAVY.  YH parameters always denote component 2.
IF (MMSD_SPEC_INDEX(1)/=1 .OR. MMSD_SPEC_INDEX(2)/=2 .OR. &
    SPECIES_MIXTURE(MMSD_SPEC_INDEX(1))%RCON<=SPECIES_MIXTURE(MMSD_SPEC_INDEX(2))%RCON) THEN
   CALL SHUTDOWN('ERROR(MMSD): SPEC_ID(1) must be the first, lighter tracked species and SPEC_ID(2) the second.') ; RETURN
ENDIF

MMSD_ID=ID; MMSD_FRAME_ID=FRAME_ID; MMSD_THERMAL_MODE=THERMAL_MODE
MMSD_REQUIRE_FRAME=REQUIRE_FRAME; MMSD_REQUIRE_PHYSICAL_PRESSURE_GAUGE=REQUIRE_PHYSICAL_PRESSURE_GAUGE
MMSD_LZ=LZ; MMSD_P_REF=P_REF; MMSD_T_REF=T_REF; MMSD_YH_MEAN=YH_MEAN; MMSD_YH_AMPLITUDE=YH_AMPLITUDE
MMSD_RHO_AMPLITUDE=RHO_AMPLITUDE; MMSD_OMEGA_M=OMEGA_M; MMSD_T_REF_M=T_REF_M
MMSD_INITIAL_STATE_TIME=INITIAL_STATE_TIME; MMSD_DIFFUSIVITY=DIFFUSIVITY
MMSD_ACTIVE=.TRUE.

END SUBROUTINE READ_MMSD


!> \brief Fail closed for the exact V2c-D verification envelope after mesh initialization.

SUBROUTINE CHECK_MMSD_SCOPE(DT)

REAL(EB), INTENT(IN) :: DT
REAL(EB) :: Y(2),RHO_A,T_A,R_A,CP_A,HS_A(2),C_A(2),S_A(2),Q_A,Q_AUDIT,Z_TEST,T_TEST,TOL, &
            K_MMS,THETA,DYDZ,D2YDZ2,DRHODZ,L_H,Y_INITIAL(2),RHO_INITIAL,T_INITIAL,R_INITIAL, &
            STATE_TOL,TRANSPORT_TOL
INTEGER :: N,NS,IZ,IT,I,J,K

IF (.NOT.MMSD_ACTIVE) RETURN
MMSD_SCOPE_ACCEPTED=.FALSE.
TOL=100._EB*EPSILON(1._EB)
STATE_TOL=2.E-5_EB
TRANSPORT_TOL=1000._EB*EPSILON(1._EB)

IF (.NOT.ALL(IEEE_IS_FINITE([DT,MMSD_LZ,MMSD_P_REF,MMSD_T_REF,MMSD_YH_MEAN,MMSD_YH_AMPLITUDE, &
                              MMSD_RHO_AMPLITUDE,MMSD_OMEGA_M,MMSD_T_REF_M,MMSD_INITIAL_STATE_TIME, &
                              MMSD_DIFFUSIVITY]))) THEN
   CALL SHUTDOWN('ERROR(MMSD): MMSD scope check received a non-finite real value.') ; RETURN
ENDIF

IF (NMESHES/=1 .OR. N_MPI_PROCESSES/=1 .OR. .NOT.TWO_D .OR. CYLINDRICAL .OR. MESHES(1)%JBAR/=1) THEN
   CALL SHUTDOWN('ERROR(MMSD): Require one-rank, one-mesh, Cartesian x-z 2-D DNS.') ; RETURN
ENDIF
IF (SIM_MODE/=DNS_MODE .OR. CONSTANT_SPECIFIC_HEAT_RATIO) THEN
   CALL SHUTDOWN('ERROR(MMSD): Require DNS_MODE and CONSTANT_SPECIFIC_HEAT_RATIO=.FALSE..') ; RETURN
ENDIF
IF (.NOT.LOCK_TIME_STEP .OR. DT<=0._EB .OR. ABS(T_BEGIN+DT)>TOL*MAX(1._EB,ABS(DT))) THEN
   CALL SHUTDOWN('ERROR(MMSD): Require LOCK_TIME_STEP=.TRUE., DT>0, and T_BEGIN+DT=0.') ; RETURN
ENDIF
IF (ABS(MMSD_P_REF-P_INF)>TOL*MAX(1._EB,ABS(P_INF)) .OR. ABS((MESHES(1)%ZF-MESHES(1)%ZS)-MMSD_LZ)> &
    TOL*MAX(1._EB,MMSD_LZ)) THEN
   CALL SHUTDOWN('ERROR(MMSD): P_REF or LZ does not match the solver domain.') ; RETURN
ENDIF
IF (ANY(ABS(GVEC)>TOL) .OR. STRATIFICATION .OR. N_REACTIONS/=0 .OR. RADIATION .OR. TURB_MODEL/=NO_TURB_MODEL .OR. &
    HVAC_SOLVE .OR. RESTART .OR. N_MOVE/=0 .OR. N_GEOM/=0 .OR. N_LAGRANGIAN_CLASSES/=0 .OR. PERIODIC_TEST/=0 .OR. &
    CC_IBM .OR. FREEZE_VELOCITY .OR. SOLID_PHASE_ONLY) THEN
   CALL SHUTDOWN('ERROR(MMSD): Gravity/reactions/radiation/turbulence/HVAC/geometry/particles/periodic tests are excluded.')
   RETURN
ENDIF
IF (MESHES(1)%N_OBST/=0) THEN
   CALL SHUTDOWN('ERROR(MMSD): OBST is outside the V2c-D empty-box scope.') ; RETURN
ENDIF
IF (.NOT.MMSD_REQUIRE_PHYSICAL_PRESSURE_GAUGE .OR. .NOT.PHYSICAL_PRESSURE_GAUGE .OR. .NOT.PHYSICAL_PRESSURE_GAUGE_READY) THEN
   CALL SHUTDOWN('ERROR(MMSD): Require the verified explicit PHYSICAL_PRESSURE_GAUGE.') ; RETURN
ENDIF
IF (MMSD_REQUIRE_FRAME) THEN
   IF (.NOT.TRANSLATING_FRAME .OR. TRIM(TF_ID)/=TRIM(MMSD_FRAME_ID) .OR. ABS(TF_AXIS(1)-1._EB)>TOL .OR. &
       ABS(TF_AXIS(2))>TOL .OR. ABS(TF_AXIS(3))>TOL) THEN
      CALL SHUTDOWN('ERROR(MMSD): REQUIRE_FRAME needs the named active +x FRAME.') ; RETURN
   ENDIF
ELSEIF (TRANSLATING_FRAME) THEN
   CALL SHUTDOWN('ERROR(MMSD): Frame-off MMSD control must not contain FRAME.') ; RETURN
ENDIF
IF (.NOT.ALLOCATED(D_Z) .OR. .NOT.ALLOCATED(K_RSQMW_Z)) THEN
   CALL SHUTDOWN('ERROR(MMSD): Species transport tables are not initialized.') ; RETURN
ENDIF
DO N=1,2
   NS=SPECIES_MIXTURE(MMSD_SPEC_INDEX(N))%SINGLE_SPEC_INDEX
   IF (NS<1) THEN
      CALL SHUTDOWN('ERROR(MMSD): Each tracked MMSD component must map to one primitive species.') ; RETURN
   ENDIF
   IF (SPECIES_MIXTURE(MMSD_SPEC_INDEX(N))%RAMP_D_INDEX>0 .OR. SPECIES_MIXTURE(MMSD_SPEC_INDEX(N))%RAMP_K_INDEX>0 .OR. &
       SPECIES(NS)%RAMP_D_INDEX>0 .OR. SPECIES(NS)%RAMP_K_INDEX>0) THEN
      CALL SHUTDOWN('ERROR(MMSD): Tracked MMSD species must not use D or K RAMPs.') ; RETURN
   ENDIF
   IF (ABS(SPECIES(NS)%D_USER-MMSD_DIFFUSIVITY)>TRANSPORT_TOL*MAX(1._EB,MMSD_DIFFUSIVITY) .OR. &
       ABS(SPECIES(NS)%K_USER)>TRANSPORT_TOL) THEN
      CALL SHUTDOWN('ERROR(MMSD): Both primitive tracked species require DIFFUSIVITY=MMSD value and CONDUCTIVITY=0.') ; RETURN
   ENDIF
   IF (.NOT.ALL(IEEE_IS_FINITE(D_Z(:,MMSD_SPEC_INDEX(N)))) .OR. .NOT.ALL(IEEE_IS_FINITE(K_RSQMW_Z(:,MMSD_SPEC_INDEX(N)))) .OR. &
       MAXVAL(ABS(D_Z(:,MMSD_SPEC_INDEX(N))-MMSD_DIFFUSIVITY))>TRANSPORT_TOL*MAX(1._EB,MMSD_DIFFUSIVITY) .OR. &
       MAXVAL(ABS(K_RSQMW_Z(:,MMSD_SPEC_INDEX(N))))>TRANSPORT_TOL) THEN
      CALL SHUTDOWN('ERROR(MMSD): Effective D_Z/K_RSQMW_Z tables do not match MMSD transport.') ; RETURN
   ENDIF
ENDDO

MMSD_Z0=MESHES(1)%ZS
Y(2)=MMSD_YH_MEAN
Y(1)=1._EB-Y(2)
CALL GET_SPECIFIC_GAS_CONSTANT(Y,R_A)
MMSD_RHO_REF=MMSD_P_REF/(MMSD_T_REF*R_A)
IF (.NOT.ALL(IEEE_IS_FINITE([MMSD_Z0,R_A,MMSD_RHO_REF]))) THEN
   CALL SHUTDOWN('ERROR(MMSD): MMSD reference-state preflight is non-finite.') ; RETURN
ENDIF
CALL POINT_TO_MESH(1)
DO K=1,KBAR
   DO J=1,JBAR
      DO I=1,IBAR
         IF (CELL(CELL_INDEX(I,J,K))%SOLID) CYCLE
         CALL MMSD_EVALUATE_STATE(ZC(K),MMSD_INITIAL_STATE_TIME,Y_INITIAL,RHO_INITIAL,T_INITIAL,R_INITIAL)
         IF (.NOT.ALL(IEEE_IS_FINITE(ZZ(I,J,K,1:2))) .OR. .NOT.ALL(IEEE_IS_FINITE([TMP(I,J,K),RHO(I,J,K)])) .OR. &
             .NOT.ALL(IEEE_IS_FINITE(Y_INITIAL)) .OR. .NOT.ALL(IEEE_IS_FINITE([RHO_INITIAL,T_INITIAL,R_INITIAL])) .OR. &
             ANY(ABS(ZZ(I,J,K,1:2)-Y_INITIAL)>STATE_TOL*MAX(1._EB,ABS(Y_INITIAL))) .OR. &
             ABS(TMP(I,J,K)-T_INITIAL)>STATE_TOL*MAX(1._EB,ABS(T_INITIAL)) .OR. &
             ABS(RHO(I,J,K)-RHO_INITIAL)>STATE_TOL*MAX(1._EB,ABS(RHO_INITIAL))) THEN
            CALL SHUTDOWN('ERROR(MMSD): Initialized gas state does not match the analytic MMSD state.') ; RETURN
         ENDIF
      ENDDO
   ENDDO
ENDDO
DO IZ=0,3
   DO IT=0,3
      Z_TEST=MMSD_Z0+MMSD_LZ*REAL(IZ,EB)/4._EB
      T_TEST=TWOPI*REAL(IT,EB)/(4._EB*MMSD_OMEGA_M)
      CALL MMSD_EVALUATE_STATE(Z_TEST,T_TEST,Y,RHO_A,T_A,R_A)
      IF (.NOT.ALL(IEEE_IS_FINITE(Y)) .OR. .NOT.ALL(IEEE_IS_FINITE([Z_TEST,T_TEST,RHO_A,T_A,R_A])) .OR. &
          MINVAL(Y)<=0._EB .OR. MAXVAL(Y)>=1._EB .OR. RHO_A<=0._EB .OR. T_A<1._EB .OR. T_A>=REAL(I_MAX_TEMP-1,EB)) THEN
         CALL SHUTDOWN('ERROR(MMSD): Analytic property preflight found an invalid state.') ; RETURN
      ENDIF
      CALL MMSD_EVALUATE_SOURCE(Z_TEST,T_TEST,S_A,Q_A,CP_A,HS_A,C_A)
      K_MMS=TWOPI/MMSD_LZ
      THETA=MMSD_OMEGA_M*T_TEST
      DYDZ=MMSD_YH_AMPLITUDE*K_MMS*COS(K_MMS*(Z_TEST-MMSD_Z0))*COS(THETA)
      D2YDZ2=-MMSD_YH_AMPLITUDE*K_MMS**2*SIN(K_MMS*(Z_TEST-MMSD_Z0))*COS(THETA)
      DRHODZ=-MMSD_RHO_REF*MMSD_RHO_AMPLITUDE*K_MMS*SIN(K_MMS*(Z_TEST-MMSD_Z0))
      L_H=MMSD_DIFFUSIVITY*(DRHODZ*DYDZ+RHO_A*D2YDZ2)
      Q_AUDIT=-CP_A*T_A*(C_A(1)*(-L_H+S_A(1))+C_A(2)*(L_H+S_A(2)))
      IF (.NOT.ALL(IEEE_IS_FINITE(S_A)) .OR. .NOT.ALL(IEEE_IS_FINITE(HS_A)) .OR. .NOT.ALL(IEEE_IS_FINITE(C_A)) .OR. &
          .NOT.ALL(IEEE_IS_FINITE([Q_A,Q_AUDIT,CP_A,K_MMS,THETA,DYDZ,D2YDZ2,DRHODZ,L_H])) .OR. &
          CP_A<=0._EB .OR. ABS(SUM(S_A))>TOL*MAX(1._EB,MAXVAL(ABS(S_A))) .OR. &
          ABS(Q_A-Q_AUDIT)>TOL*MAX(1._EB,ABS(Q_A),ABS(Q_AUDIT))) THEN
         CALL SHUTDOWN('ERROR(MMSD): Analytic source/property preflight failed.') ; RETURN
      ENDIF
   ENDDO
ENDDO
MMSD_SCOPE_ACCEPTED=.TRUE.

END SUBROUTINE CHECK_MMSD_SCOPE


!> \brief Evaluate the analytic static-density EOS state at physical coordinate z and time t.
!> SPEC_ID(1) is LIGHT and SPEC_ID(2) is HEAVY; YH is therefore component 2.

SUBROUTINE MMSD_EVALUATE_STATE(Z,T,Y,RHO_A,T_A,RMIX)

REAL(EB), INTENT(IN) :: Z,T
REAL(EB), INTENT(OUT) :: Y(2),RHO_A,T_A,RMIX
REAL(EB) :: K_MMS,THETA

K_MMS=TWOPI/MMSD_LZ
THETA=MMSD_OMEGA_M*(T-MMSD_T_REF_M)
Y(2)=MMSD_YH_MEAN+MMSD_YH_AMPLITUDE*SIN(K_MMS*(Z-MMSD_Z0))*COS(THETA)
Y(1)=1._EB-Y(2)
CALL GET_SPECIFIC_GAS_CONSTANT(Y,RMIX)
RHO_A=MMSD_RHO_REF*(1._EB+MMSD_RHO_AMPLITUDE*COS(K_MMS*(Z-MMSD_Z0)))
T_A=MMSD_P_REF/(RHO_A*RMIX)

END SUBROUTINE MMSD_EVALUATE_STATE


!> \brief Evaluate conservative species and thermal sources using analytic state only.
!> L_H and S_H belong to the HEAVY component, SPEC_ID(2); SPEC_ID(1) is LIGHT.

SUBROUTINE MMSD_EVALUATE_SOURCE(Z,T,S,Q_MMS,CP_A,HS_A,C_A)

REAL(EB), INTENT(IN) :: Z,T
REAL(EB), INTENT(OUT) :: S(2),Q_MMS,CP_A,HS_A(2),C_A(2)
REAL(EB) :: Y(2),RHO_A,T_A,RMIX,K_MMS,THETA,DYDT,DYDZ,D2YDZ2,DRHODZ,L_H
INTEGER :: N

CALL MMSD_EVALUATE_STATE(Z,T,Y,RHO_A,T_A,RMIX)
K_MMS=TWOPI/MMSD_LZ
THETA=MMSD_OMEGA_M*(T-MMSD_T_REF_M)
DYDT=-MMSD_YH_AMPLITUDE*MMSD_OMEGA_M*SIN(K_MMS*(Z-MMSD_Z0))*SIN(THETA)
DYDZ=MMSD_YH_AMPLITUDE*K_MMS*COS(K_MMS*(Z-MMSD_Z0))*COS(THETA)
D2YDZ2=-MMSD_YH_AMPLITUDE*K_MMS**2*SIN(K_MMS*(Z-MMSD_Z0))*COS(THETA)
DRHODZ=-MMSD_RHO_REF*MMSD_RHO_AMPLITUDE*K_MMS*SIN(K_MMS*(Z-MMSD_Z0))
L_H=MMSD_DIFFUSIVITY*(DRHODZ*DYDZ+RHO_A*D2YDZ2)
S(2)=RHO_A*DYDT-L_H
S(1)=-S(2)
CALL GET_SPECIFIC_HEAT(Y,CP_A,T_A)
DO N=1,2
   CALL GET_SENSIBLE_ENTHALPY_Z(MMSD_SPEC_INDEX(N),T_A,HS_A(N))
   C_A(N)=SPECIES_MIXTURE(MMSD_SPEC_INDEX(N))%RCON/RMIX-HS_A(N)/(CP_A*T_A)
ENDDO
Q_MMS=-RHO_A*CP_A*T_A*(C_A(2)*DYDT-C_A(1)*DYDT)

END SUBROUTINE MMSD_EVALUATE_SOURCE


!> \brief Add endpoint-weighted analytic species source to the density update.

SUBROUTINE MMSD_ADD_DENSITY_STAGE(T,DT,NM,PREDICTOR_STAGE)

REAL(EB), INTENT(IN) :: T,DT
INTEGER, INTENT(IN) :: NM
LOGICAL, INTENT(IN) :: PREDICTOR_STAGE
REAL(EB) :: S(2),Q_MMS,CP_A,HS_A(2),C_A(2),WGT
INTEGER :: I,J,K

IF (.NOT.MMSD_ACTIVE .OR. .NOT.MMSD_SCOPE_ACCEPTED) RETURN
CALL POINT_TO_MESH(NM)
WGT=DT
IF (.NOT.PREDICTOR_STAGE) WGT=0.5_EB*DT
!$OMP PARALLEL DO PRIVATE(S,Q_MMS,CP_A,HS_A,C_A) SCHEDULE(STATIC)
DO K=1,KBAR
   DO J=1,JBAR
      DO I=1,IBAR
         IF (CELL(CELL_INDEX(I,J,K))%SOLID) CYCLE
         CALL MMSD_EVALUATE_SOURCE(ZC(K),T,S,Q_MMS,CP_A,HS_A,C_A)
         IF (PREDICTOR_STAGE) THEN
            ZZS(I,J,K,MMSD_SPEC_INDEX(1))=ZZS(I,J,K,MMSD_SPEC_INDEX(1))+WGT*S(1)
            ZZS(I,J,K,MMSD_SPEC_INDEX(2))=ZZS(I,J,K,MMSD_SPEC_INDEX(2))+WGT*S(2)
         ELSE
            ZZ(I,J,K,MMSD_SPEC_INDEX(1))=ZZ(I,J,K,MMSD_SPEC_INDEX(1))+WGT*S(1)
            ZZ(I,J,K,MMSD_SPEC_INDEX(2))=ZZ(I,J,K,MMSD_SPEC_INDEX(2))+WGT*S(2)
         ENDIF
      ENDDO
   ENDDO
ENDDO
!$OMP END PARALLEL DO

END SUBROUTINE MMSD_ADD_DENSITY_STAGE


!> \brief Add raw volumetric Q_MMS before FDS applies 1/(rho cp T).

SUBROUTINE MMSD_ADD_DIVERGENCE_HEAT(T_STATE,NM,DP)

REAL(EB), INTENT(IN) :: T_STATE
INTEGER, INTENT(IN) :: NM
REAL(EB), INTENT(INOUT) :: DP(0:,0:,0:)
REAL(EB) :: S(2),Q_MMS,CP_A,HS_A(2),C_A(2)
INTEGER :: I,J,K

IF (.NOT.MMSD_ACTIVE .OR. .NOT.MMSD_SCOPE_ACCEPTED) RETURN
CALL POINT_TO_MESH(NM)
!$OMP PARALLEL DO PRIVATE(S,Q_MMS,CP_A,HS_A,C_A) SCHEDULE(STATIC)
DO K=1,KBAR
   DO J=1,JBAR
      DO I=1,IBAR
         IF (CELL(CELL_INDEX(I,J,K))%SOLID) CYCLE
         CALL MMSD_EVALUATE_SOURCE(ZC(K),T_STATE,S,Q_MMS,CP_A,HS_A,C_A)
         DP(I,J,K)=DP(I,J,K)+Q_MMS
      ENDDO
   ENDDO
ENDDO
!$OMP END PARALLEL DO

END SUBROUTINE MMSD_ADD_DIVERGENCE_HEAT


!> \brief Add analytic C_i S_i/rho after ordinary species diffusion, outside reaction logic.

SUBROUTINE MMSD_ADD_DIVERGENCE_SPECIES(T_STATE,NM,DP)

REAL(EB), INTENT(IN) :: T_STATE
INTEGER, INTENT(IN) :: NM
REAL(EB), INTENT(INOUT) :: DP(0:,0:,0:)
REAL(EB) :: S(2),Q_MMS,CP_A,HS_A(2),C_A(2),Y(2),RHO_A,T_A,RMIX
INTEGER :: I,J,K

IF (.NOT.MMSD_ACTIVE .OR. .NOT.MMSD_SCOPE_ACCEPTED) RETURN
CALL POINT_TO_MESH(NM)
!$OMP PARALLEL DO PRIVATE(S,Q_MMS,CP_A,HS_A,C_A,Y,RHO_A,T_A,RMIX) SCHEDULE(STATIC)
DO K=1,KBAR
   DO J=1,JBAR
      DO I=1,IBAR
         IF (CELL(CELL_INDEX(I,J,K))%SOLID) CYCLE
         CALL MMSD_EVALUATE_STATE(ZC(K),T_STATE,Y,RHO_A,T_A,RMIX)
         CALL MMSD_EVALUATE_SOURCE(ZC(K),T_STATE,S,Q_MMS,CP_A,HS_A,C_A)
         DP(I,J,K)=DP(I,J,K)+(C_A(1)*S(1)+C_A(2)*S(2))/RHO_A
      ENDDO
   ENDDO
ENDDO
!$OMP END PARALLEL DO

END SUBROUTINE MMSD_ADD_DIVERGENCE_SPECIES


!> \brief Write an activation marker and frozen analytic parameters; no solution state is modified.

SUBROUTINE MMSD_WRITE_DIAGNOSTICS(INITIAL_STATE_TIME,NM)

REAL(EB), INTENT(IN) :: INITIAL_STATE_TIME
INTEGER, INTENT(IN) :: NM

IF (.NOT.MMSD_ACTIVE .OR. .NOT.MMSD_SCOPE_ACCEPTED .OR. MMSD_DIAGNOSTICS_WRITTEN) RETURN
IF (MY_RANK==0 .AND. OUT_FILE_OPENED) THEN
   WRITE(LU_OUTPUT,'(A,A)') ' V2c-D MMSD enabled: ',TRIM(MMSD_ID)
   WRITE(LU_OUTPUT,'(A,ES13.6,A,I0)') '   MMSD analytic initial state time (s): ',INITIAL_STATE_TIME,', mesh: ',NM
   WRITE(LU_OUTPUT,'(A,5(ES13.6,1X))') '   LZ, P_REF, T_REF, D, OMEGA_M: ', &
      MMSD_LZ,MMSD_P_REF,MMSD_T_REF,MMSD_DIFFUSIVITY,MMSD_OMEGA_M
   WRITE(LU_OUTPUT,'(A,3(ES13.6,1X))') '   YH mean/amplitude, rho amplitude: ',MMSD_YH_MEAN,MMSD_YH_AMPLITUDE,MMSD_RHO_AMPLITUDE
ENDIF
MMSD_DIAGNOSTICS_WRITTEN=.TRUE.

END SUBROUTINE MMSD_WRITE_DIAGNOSTICS


!> \brief Return opt-in analytic/source diagnostic values for gas-phase output quantities 590:600.

REAL(EB) FUNCTION MMSD_OUTPUT_VALUE(T,Z,OUTPUT_CODE) RESULT(VALUE)

REAL(EB), INTENT(IN) :: T,Z
INTEGER, INTENT(IN) :: OUTPUT_CODE
REAL(EB) :: Y(2),RHO_A,T_A,RMIX,S(2),Q_MMS,CP_A,HS_A(2),C_A(2),T_EVALUATE

VALUE=0._EB
IF (.NOT.MMSD_ACTIVE .OR. .NOT.MMSD_SCOPE_ACCEPTED) RETURN
T_EVALUATE=T
IF (INITIALIZATION_PHASE) T_EVALUATE=MMSD_INITIAL_STATE_TIME
CALL MMSD_EVALUATE_STATE(Z,T_EVALUATE,Y,RHO_A,T_A,RMIX)
CALL MMSD_EVALUATE_SOURCE(Z,T_EVALUATE,S,Q_MMS,CP_A,HS_A,C_A)
SELECT CASE(OUTPUT_CODE)
   CASE(590); VALUE=Y(2) ! Y_H: SPEC_ID(2), HEAVY
   CASE(591); VALUE=T_A-TMPM
   CASE(592); VALUE=RHO_A
   CASE(593); VALUE=S(1) ! S_L: SPEC_ID(1), LIGHT
   CASE(594); VALUE=S(2) ! S_H: SPEC_ID(2), HEAVY
   CASE(595); VALUE=0.001_EB*Q_MMS
   CASE(596); VALUE=CP_A
   CASE(597); VALUE=HS_A(1)
   CASE(598); VALUE=HS_A(2)
   CASE(599); VALUE=RMIX
   CASE(600); VALUE=SUM(S)
END SELECT

END FUNCTION MMSD_OUTPUT_VALUE


