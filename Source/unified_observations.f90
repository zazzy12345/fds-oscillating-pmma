!> \brief Default-off observation support for the G2 unified successor.
MODULE UNIFIED_OBSERVATIONS

USE PRECISION_PARAMETERS
USE GLOBAL_CONSTANTS

IMPLICIT NONE (TYPE,EXTERNAL)
PRIVATE

CHARACTER(LEN=*), PARAMETER :: UOBS_SCHEMA='g2-unified-successor-source-v2'
CHARACTER(LEN=*), PARAMETER :: UOBS_RELEASE_DIFF=&
   '9413c9cce52526559978f8a99c8426004bb77ca94cb5dde446aafe9a07a44f49'

PUBLIC UOBS_ACTIVE,UOBS_CLOCK_SELECTED,UOBS_SELECTED_INDEX,UOBS_SAMPLE_SLOT
PUBLIC UOBS_HEAD,UOBS_ADD_TEXT,UOBS_ADD_INT,UOBS_ADD_LOGICAL,UOBS_ADD_REAL,UOBS_ADD_VEC3
PUBLIC UOBS_EMIT_WALL,UOBS_EMIT_RADIATION,UOBS_EMIT_PACKET,UOBS_GET_MANIFEST

CONTAINS

LOGICAL FUNCTION UOBS_HEX64(VALUE)
CHARACTER(LEN=*), INTENT(IN) :: VALUE
INTEGER :: I
UOBS_HEX64=.FALSE.
IF (LEN_TRIM(VALUE)/=64 .OR. VALUE==REPEAT('0',64)) RETURN
DO I=1,64
   IF (INDEX('0123456789abcdef',VALUE(I:I))==0) RETURN
ENDDO
UOBS_HEX64=.TRUE.
END FUNCTION UOBS_HEX64

LOGICAL FUNCTION UOBS_ENV_HEX64(NAME,EXPECTED)
CHARACTER(LEN=*), INTENT(IN) :: NAME
CHARACTER(LEN=*), INTENT(IN), OPTIONAL :: EXPECTED
CHARACTER(LEN=64) :: VALUE
INTEGER :: LENGTH_VALUE,STATUS_VALUE
UOBS_ENV_HEX64=.FALSE. ; VALUE=''
CALL GET_ENVIRONMENT_VARIABLE(NAME,VALUE,LENGTH=LENGTH_VALUE,STATUS=STATUS_VALUE)
IF (STATUS_VALUE/=0 .OR. LENGTH_VALUE/=64) RETURN
IF (.NOT.UOBS_HEX64(VALUE)) RETURN
IF (PRESENT(EXPECTED)) THEN
   IF (VALUE/=EXPECTED) RETURN
ENDIF
UOBS_ENV_HEX64=.TRUE.
END FUNCTION UOBS_ENV_HEX64


LOGICAL FUNCTION UOBS_V7_CHID_REGISTERED()
UOBS_V7_CHID_REGISTERED=.FALSE.
SELECT CASE(TRIM(CHID))
   CASE('tf_g2v7_v7a_normal_nt0100')
   CASE('tf_g2v7_v7a_normal_nt0200')
   CASE('tf_g2v7_v7a_normal_nt0400')
   CASE('tf_g2v7_v7a_normal_nt0800')
   CASE('tf_g2v7_v7b_g0_nt0200')
   CASE('tf_g2v7_v7b_g0_nt0400')
   CASE('tf_g2v7_v7b_g0_nt0800')
   CASE('tf_g2v7_v7b_g1_nt0800')
   CASE('tf_g2v7_v7c_passive_d1')
   CASE('tf_g2v7_v7c_passive_d1p5')
   CASE('tf_g2v7_v7c_passive_d2')
   CASE('tf_g2v7_v7c_thermal_d1')
   CASE('tf_g2v7_v7c_thermal_d1p5')
   CASE('tf_g2v7_v7c_thermal_d2')
   CASE('tf_g2v7_v7c_vortex_d1')
   CASE('tf_g2v7_v7c_vortex_d1p5')
   CASE('tf_g2v7_v7c_vortex_d2')
      UOBS_V7_CHID_REGISTERED=.TRUE.
END SELECT
END FUNCTION UOBS_V7_CHID_REGISTERED

LOGICAL FUNCTION UOBS_ACTIVE(FEATURE,NM)
CHARACTER(LEN=*), INTENT(IN) :: FEATURE
INTEGER, INTENT(IN) :: NM
CHARACTER(LEN=32) :: VALUE
INTEGER :: LENGTH_VALUE,STATUS_VALUE
UOBS_ACTIVE=.FALSE. ; VALUE=''
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_OBSERVATIONS',VALUE,&
                              LENGTH=LENGTH_VALUE,STATUS=STATUS_VALUE)
IF (STATUS_VALUE/=0 .OR. LENGTH_VALUE/=1 .OR. VALUE(1:1)/='1') RETURN
VALUE=''
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_FEATURE',VALUE,&
                              LENGTH=LENGTH_VALUE,STATUS=STATUS_VALUE)
IF (STATUS_VALUE/=0 .OR. VALUE(1:LENGTH_VALUE)/=TRIM(FEATURE)) RETURN
IF (TRIM(FEATURE)=='V7' .AND. .NOT.UOBS_V7_CHID_REGISTERED()) RETURN
VALUE=''
CALL GET_ENVIRONMENT_VARIABLE('OMP_NUM_THREADS',VALUE,LENGTH=LENGTH_VALUE,STATUS=STATUS_VALUE)
IF (STATUS_VALUE/=0 .OR. LENGTH_VALUE/=1 .OR. VALUE(1:1)/='1') RETURN
IF (NM/=1 .OR. NMESHES/=1 .OR. MY_RANK/=0 .OR. N_MPI_PROCESSES/=1) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_SOURCE_DIFF_SHA256')) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_BINARY_SHA256')) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_BUILD_RECEIPT_SHA256')) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_REFERENCE_CODE_SHA256')) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_REFERENCE_RECEIPT_SHA256')) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_TOOLS_MANIFEST_SHA256')) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_ROOTS_MANIFEST_SHA256')) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_OBSERVATION_MANIFEST_SHA256')) RETURN
IF (.NOT.UOBS_ENV_HEX64('FDS_UNIFIED_SUCCESSOR_CLOCK_MANIFEST_SHA256')) RETURN
UOBS_ACTIVE=.TRUE.
END FUNCTION UOBS_ACTIVE

CHARACTER(LEN=16) FUNCTION UOBS_BITS(VALUE)
REAL(EB), INTENT(IN) :: VALUE
INTEGER(8) :: RAW
RAW=TRANSFER(VALUE,RAW)
WRITE(UOBS_BITS,'(Z16.16)') RAW
END FUNCTION UOBS_BITS

LOGICAL FUNCTION UOBS_CLOCK_SELECTED(T)
REAL(EB), INTENT(IN) :: T
CHARACTER(LEN=8192) :: CLOCKS,SEARCH
INTEGER :: LENGTH_VALUE,STATUS_VALUE
UOBS_CLOCK_SELECTED=.FALSE. ; CLOCKS=''
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_CLOCK_BITS',CLOCKS,&
                              LENGTH=LENGTH_VALUE,STATUS=STATUS_VALUE)
IF (STATUS_VALUE/=0 .OR. LENGTH_VALUE<16 .OR. LENGTH_VALUE>LEN(CLOCKS)) RETURN
SEARCH=','//CLOCKS(1:LENGTH_VALUE)//','
UOBS_CLOCK_SELECTED=INDEX(SEARCH,','//UOBS_BITS(T)//',')>0
END FUNCTION UOBS_CLOCK_SELECTED

INTEGER FUNCTION UOBS_SELECTED_INDEX(NAME)
CHARACTER(LEN=*), INTENT(IN) :: NAME
CHARACTER(LEN=32) :: VALUE
INTEGER :: IOS,LENGTH_VALUE,STATUS_VALUE
UOBS_SELECTED_INDEX=-1 ; VALUE=''
CALL GET_ENVIRONMENT_VARIABLE(NAME,VALUE,LENGTH=LENGTH_VALUE,STATUS=STATUS_VALUE)
IF (STATUS_VALUE/=0 .OR. LENGTH_VALUE<1) RETURN
READ(VALUE(1:LENGTH_VALUE),*,IOSTAT=IOS) UOBS_SELECTED_INDEX
IF (IOS/=0 .OR. UOBS_SELECTED_INDEX<1) UOBS_SELECTED_INDEX=-1
END FUNCTION UOBS_SELECTED_INDEX

INTEGER FUNCTION UOBS_Q(N,F)
INTEGER, INTENT(IN) :: N
REAL(EB), INTENT(IN) :: F
UOBS_Q=MAX(1,MIN(N,NINT(F*REAL(N+1,EB))))
END FUNCTION UOBS_Q

INTEGER FUNCTION UOBS_SAMPLE_SLOT(IOR,I,J,K,IBAR,JBAR,KBAR)
INTEGER, INTENT(IN) :: IOR,I,J,K,IBAR,JBAR,KBAR
INTEGER :: A,B,NA,NB,A1,A2,A3,B1,B2,B3
UOBS_SAMPLE_SLOT=0
SELECT CASE(ABS(IOR))
   CASE(1); A=J ; B=K ; NA=JBAR ; NB=KBAR
   CASE(2); A=I ; B=K ; NA=IBAR ; NB=KBAR
   CASE(3); A=I ; B=J ; NA=IBAR ; NB=JBAR
END SELECT
A1=UOBS_Q(NA,0.25_EB) ; A2=UOBS_Q(NA,0.50_EB) ; A3=UOBS_Q(NA,0.75_EB)
B1=UOBS_Q(NB,0.25_EB) ; B2=UOBS_Q(NB,0.50_EB) ; B3=UOBS_Q(NB,0.75_EB)
IF (A==A2 .AND. B==B2) UOBS_SAMPLE_SLOT=1
IF (A==A1 .AND. B==B1) UOBS_SAMPLE_SLOT=2
IF (A==A1 .AND. B==B3) UOBS_SAMPLE_SLOT=3
IF (A==A3 .AND. B==B1) UOBS_SAMPLE_SLOT=4
IF (A==A3 .AND. B==B3) UOBS_SAMPLE_SLOT=5
END FUNCTION UOBS_SAMPLE_SLOT

SUBROUTINE UOBS_GET_MANIFEST(VALUE)
CHARACTER(LEN=64), INTENT(OUT) :: VALUE
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_OBSERVATION_MANIFEST_SHA256',VALUE)
END SUBROUTINE UOBS_GET_MANIFEST

CHARACTER(LEN=8192) FUNCTION UOBS_HEAD(FEATURE,KIND,T,NM)
CHARACTER(LEN=*), INTENT(IN) :: FEATURE,KIND
REAL(EB), INTENT(IN) :: T
INTEGER, INTENT(IN) :: NM
CHARACTER(LEN=64) :: MANIFEST,CLOCK_MANIFEST,SOURCE_DIFF,BINARY,BUILD,REF_CODE,REF_RECEIPT,TOOLS,ROOTS
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_OBSERVATION_MANIFEST_SHA256',MANIFEST)
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_CLOCK_MANIFEST_SHA256',CLOCK_MANIFEST)
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_SOURCE_DIFF_SHA256',SOURCE_DIFF)
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_BINARY_SHA256',BINARY)
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_BUILD_RECEIPT_SHA256',BUILD)
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_REFERENCE_CODE_SHA256',REF_CODE)
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_REFERENCE_RECEIPT_SHA256',REF_RECEIPT)
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_TOOLS_MANIFEST_SHA256',TOOLS)
CALL GET_ENVIRONMENT_VARIABLE('FDS_UNIFIED_SUCCESSOR_ROOTS_MANIFEST_SHA256',ROOTS)
UOBS_HEAD='UNIFIED_SUCCESSOR_OBS schema='//UOBS_SCHEMA
CALL UOBS_ADD_TEXT(UOBS_HEAD,'feature',FEATURE) ; CALL UOBS_ADD_TEXT(UOBS_HEAD,'kind',KIND)
CALL UOBS_ADD_TEXT(UOBS_HEAD,'release_diff',UOBS_RELEASE_DIFF)
CALL UOBS_ADD_TEXT(UOBS_HEAD,'source_diff',SOURCE_DIFF) ; CALL UOBS_ADD_TEXT(UOBS_HEAD,'binary',BINARY)
CALL UOBS_ADD_TEXT(UOBS_HEAD,'build_receipt',BUILD) ; CALL UOBS_ADD_TEXT(UOBS_HEAD,'reference_code',REF_CODE)
CALL UOBS_ADD_TEXT(UOBS_HEAD,'reference_receipt',REF_RECEIPT) ; CALL UOBS_ADD_TEXT(UOBS_HEAD,'tools',TOOLS)
CALL UOBS_ADD_TEXT(UOBS_HEAD,'roots',ROOTS) ; CALL UOBS_ADD_TEXT(UOBS_HEAD,'manifest',MANIFEST)
CALL UOBS_ADD_TEXT(UOBS_HEAD,'clock_manifest',CLOCK_MANIFEST) ; CALL UOBS_ADD_TEXT(UOBS_HEAD,'chid',CHID)
CALL UOBS_ADD_INT(UOBS_HEAD,'rank',MY_RANK) ; CALL UOBS_ADD_INT(UOBS_HEAD,'mesh',NM)
CALL UOBS_ADD_INT(UOBS_HEAD,'icyc',ICYC) ; CALL UOBS_ADD_LOGICAL(UOBS_HEAD,'predictor',PREDICTOR)
CALL UOBS_ADD_REAL(UOBS_HEAD,'t',T)
END FUNCTION UOBS_HEAD

SUBROUTINE UOBS_ADD_TEXT(LINE,NAME,VALUE)
CHARACTER(LEN=*), INTENT(INOUT) :: LINE
CHARACTER(LEN=*), INTENT(IN) :: NAME,VALUE
LINE=TRIM(LINE)//' '//TRIM(NAME)//'='//TRIM(VALUE)
END SUBROUTINE UOBS_ADD_TEXT

SUBROUTINE UOBS_ADD_INT(LINE,NAME,VALUE)
CHARACTER(LEN=*), INTENT(INOUT) :: LINE
CHARACTER(LEN=*), INTENT(IN) :: NAME
INTEGER, INTENT(IN) :: VALUE
CHARACTER(LEN=32) :: TEXT
WRITE(TEXT,'(I0)') VALUE ; CALL UOBS_ADD_TEXT(LINE,NAME,TEXT)
END SUBROUTINE UOBS_ADD_INT

SUBROUTINE UOBS_ADD_LOGICAL(LINE,NAME,VALUE)
CHARACTER(LEN=*), INTENT(INOUT) :: LINE
CHARACTER(LEN=*), INTENT(IN) :: NAME
LOGICAL, INTENT(IN) :: VALUE
CALL UOBS_ADD_TEXT(LINE,NAME,MERGE('1','0',VALUE))
END SUBROUTINE UOBS_ADD_LOGICAL

SUBROUTINE UOBS_ADD_REAL(LINE,NAME,VALUE)
CHARACTER(LEN=*), INTENT(INOUT) :: LINE
CHARACTER(LEN=*), INTENT(IN) :: NAME
REAL(EB), INTENT(IN) :: VALUE
CHARACTER(LEN=32) :: TEXT
WRITE(TEXT,'(ES24.16E3)') VALUE ; CALL UOBS_ADD_TEXT(LINE,NAME,ADJUSTL(TEXT))
CALL UOBS_ADD_TEXT(LINE,TRIM(NAME)//'_bits',UOBS_BITS(VALUE))
END SUBROUTINE UOBS_ADD_REAL

SUBROUTINE UOBS_ADD_VEC3(LINE,NAME,VALUE)
CHARACTER(LEN=*), INTENT(INOUT) :: LINE
CHARACTER(LEN=*), INTENT(IN) :: NAME
REAL(EB), INTENT(IN) :: VALUE(3)
INTEGER :: N
DO N=1,3
   CALL UOBS_ADD_REAL(LINE,TRIM(NAME)//'_'//ACHAR(IACHAR('x')+N-1),VALUE(N))
ENDDO
END SUBROUTINE UOBS_ADD_VEC3

SUBROUTINE UOBS_EMIT_WALL(T,NM,IW,STAGE,CALL_HT,DT_BC,DT_SUB,N_SUB,TMP_G,TMP_F,RDN,K_G,HTC,Q_CON)
REAL(EB), INTENT(IN) :: T,DT_BC,DT_SUB,TMP_G,TMP_F,RDN,K_G,HTC,Q_CON
INTEGER, INTENT(IN) :: NM,IW,N_SUB
LOGICAL, INTENT(IN) :: CALL_HT
CHARACTER(LEN=*), INTENT(IN) :: STAGE
CHARACTER(LEN=8192) :: LINE
IF (.NOT.UOBS_ACTIVE('V9',NM) .OR. .NOT.UOBS_CLOCK_SELECTED(T)) RETURN
LINE=UOBS_HEAD('V9','wall_stage',T,NM) ; CALL UOBS_ADD_TEXT(LINE,'stage',STAGE)
CALL UOBS_ADD_INT(LINE,'wall_index',IW) ; CALL UOBS_ADD_INT(LINE,'wall_counter',WALL_COUNTER)
CALL UOBS_ADD_LOGICAL(LINE,'call_ht_1d',CALL_HT) ; CALL UOBS_ADD_REAL(LINE,'dt_bc',DT_BC)
CALL UOBS_ADD_REAL(LINE,'dt_bc_sub',DT_SUB) ; CALL UOBS_ADD_INT(LINE,'n_substeps',N_SUB)
CALL UOBS_ADD_REAL(LINE,'tmp_g',TMP_G) ; CALL UOBS_ADD_REAL(LINE,'tmp_f',TMP_F)
CALL UOBS_ADD_REAL(LINE,'rdn',RDN) ; CALL UOBS_ADD_REAL(LINE,'k_g',K_G)
CALL UOBS_ADD_REAL(LINE,'heat_trans_coef',HTC) ; CALL UOBS_ADD_REAL(LINE,'q_con_f',Q_CON)
WRITE(LU_OUTPUT,'(A)') TRIM(LINE)
END SUBROUTINE UOBS_EMIT_WALL

SUBROUTINE UOBS_EMIT_RADIATION(T,NM,IW,STAGE,RAD_ITER,ACTUAL_UPDATE,RAD_CALL,TIME_INC,ANGLE_COUNT,ANGLE_INC,&
                               COMPLETE,Q_IN,Q_OUT)
REAL(EB), INTENT(IN) :: T,Q_IN,Q_OUT
INTEGER, INTENT(IN) :: NM,IW,RAD_ITER,RAD_CALL,TIME_INC,ANGLE_COUNT,ANGLE_INC
LOGICAL, INTENT(IN) :: ACTUAL_UPDATE,COMPLETE
CHARACTER(LEN=*), INTENT(IN) :: STAGE
CHARACTER(LEN=8192) :: LINE
IF (.NOT.UOBS_ACTIVE('V9R',NM) .OR. .NOT.UOBS_CLOCK_SELECTED(T)) RETURN
LINE=UOBS_HEAD('V9R','radiation_stage',T,NM) ; CALL UOBS_ADD_TEXT(LINE,'stage',STAGE)
CALL UOBS_ADD_INT(LINE,'wall_index',IW) ; CALL UOBS_ADD_INT(LINE,'rad_iter',RAD_ITER)
CALL UOBS_ADD_LOGICAL(LINE,'actual_update',ACTUAL_UPDATE) ; CALL UOBS_ADD_INT(LINE,'rad_call_counter',RAD_CALL)
CALL UOBS_ADD_INT(LINE,'time_step_increment',TIME_INC) ; CALL UOBS_ADD_INT(LINE,'angle_inc_counter',ANGLE_COUNT)
CALL UOBS_ADD_INT(LINE,'angle_increment',ANGLE_INC) ; CALL UOBS_ADD_LOGICAL(LINE,'radiation_completed',COMPLETE)
CALL UOBS_ADD_REAL(LINE,'q_rad_in',Q_IN) ; CALL UOBS_ADD_REAL(LINE,'q_rad_out',Q_OUT)
WRITE(LU_OUTPUT,'(A)') TRIM(LINE)
END SUBROUTINE UOBS_EMIT_RADIATION

SUBROUTINE UOBS_EMIT_PACKET(T,NM,KIND,CENTER,SIGMA,PEAK,INTEGRAL,KE,DIV_MAX,DIV_LIMIT)
REAL(EB), INTENT(IN) :: T,CENTER(3),SIGMA,PEAK,INTEGRAL,KE,DIV_MAX,DIV_LIMIT
INTEGER, INTENT(IN) :: NM
CHARACTER(LEN=*), INTENT(IN) :: KIND
CHARACTER(LEN=8192) :: LINE
IF (.NOT.UOBS_ACTIVE('V7',NM)) RETURN
LINE=UOBS_HEAD('V7','packet_receipt',T,NM) ; CALL UOBS_ADD_TEXT(LINE,'packet_kind',KIND)
CALL UOBS_ADD_VEC3(LINE,'packet_center',CENTER) ; CALL UOBS_ADD_REAL(LINE,'packet_sigma',SIGMA)
CALL UOBS_ADD_REAL(LINE,'packet_peak',PEAK)
CALL UOBS_ADD_REAL(LINE,'packet_integral',INTEGRAL) ; CALL UOBS_ADD_REAL(LINE,'kinetic_energy',KE)
CALL UOBS_ADD_REAL(LINE,'max_discrete_divergence',DIV_MAX) ; CALL UOBS_ADD_REAL(LINE,'divergence_limit',DIV_LIMIT)
WRITE(LU_OUTPUT,'(A)') TRIM(LINE)
END SUBROUTINE UOBS_EMIT_PACKET

END MODULE UNIFIED_OBSERVATIONS
